"""Code-writing sub-agent.

For a given :class:`ModuleSpec`, the code writer produces one or more source
files. To keep the working demo reliable without network access, we use
deterministic templates keyed by the module's ``kind``. When an LLM is
configured and produces well-formed JSON, its output is merged in — but the
deterministic templates always seed the module so the pipeline can finish
end-to-end even when all providers are unreachable (e.g. CI).
"""

