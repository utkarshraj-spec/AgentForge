def run(spec: EngineeringSpec, module: ModuleSpec, context: SharedContext) -> ModuleArtifact:
    """Produce a :class:`ModuleArtifact` for *module*."""

    files: dict[str, str] = {}
    template = _TEMPLATES.get(module.kind)
    if template is not None:
        files.update(template(spec))

    # Try the LLM too; merge any new files it proposes.
    provider = get_provider()
    try:
        raw = provider.complete(
            [
                Message(role="system", content=_SYSTEM_PROMPT),
                Message(
                    role="user",
                    content=(
                        f"Project: {spec.project_name}\n"
                        f"Module: {module.name} ({module.kind})\n"
                        f"Description: {module.description}\n"
                        f"Acceptance criteria: {module.acceptance_criteria}\n"
                        f"Target stack: {spec.target_stack}\n"
                    ),
                ),
            ],
            temperature=0.2,
        )
        data = extract_json(raw)
        for path, content in (data.get("files") or {}).items():
            if path not in files and isinstance(content, str):
                files[path] = content
    except Exception as exc:
        logger.debug("code_writer LLM call skipped: %s", exc)

    artifact = ModuleArtifact(
        module=module.name,
        agent="code_writer",
        files=files,
        notes=f"Generated {len(files)} files for module {module.name} ({module.kind}).",
    )
    context.audit(
        "code_writer",
        "module_built",
        {"module": module.name, "files": list(files.keys())},
    )
    for path in files:
        context.remember(
            f"code_writer produced {path} for {module.name}",
            metadata={"module": module.name, "file": path, "kind": module.kind},
        )
    return artifact
