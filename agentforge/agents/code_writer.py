def _security_module(spec: EngineeringSpec) -> dict[str, str]:
    return {
        f"{spec.project_name}/security.py": '''"""Security middleware: headers, basic rate limiting."""

from __future__ import annotations

import time
from collections import defaultdict, deque
from typing import Callable

from fastapi import FastAPI, HTTPException, Request
from starlette.middleware.base import BaseHTTPMiddleware
from starlette.responses import Response


class SecurityHeadersMiddleware(BaseHTTPMiddleware):
    """Attach a baseline set of security headers to every response."""

    HEADERS = {
        "X-Content-Type-Options": "nosniff",
        "X-Frame-Options": "DENY",
        "Referrer-Policy": "no-referrer",
        "Strict-Transport-Security": "max-age=63072000; includeSubDomains",
        "Content-Security-Policy": "default-src 'self'",
    }

    async def dispatch(self, request: Request, call_next: Callable) -> Response:
        response = await call_next(request)
        for key, value in self.HEADERS.items():
            response.headers.setdefault(key, value)
        return response


class InMemoryRateLimiter(BaseHTTPMiddleware):
    """Very small fixed-window rate limiter for dev/demo use."""

    def __init__(self, app, *, requests_per_minute: int = 120) -> None:
        super().__init__(app)
        self.rpm = requests_per_minute
        self._hits: dict[str, deque[float]] = defaultdict(deque)

    async def dispatch(self, request: Request, call_next: Callable) -> Response:
        now = time.monotonic()
        ip = request.client.host if request.client else "unknown"
        window = self._hits[ip]
        while window and now - window[0] > 60:
            window.popleft()
        if len(window) >= self.rpm:
            raise HTTPException(status_code=429, detail="Too Many Requests")
        window.append(now)
        return await call_next(request)


def install(app: FastAPI) -> None:
    """Attach security middleware to the FastAPI app."""
    app.add_middleware(SecurityHeadersMiddleware)
    app.add_middleware(InMemoryRateLimiter)
''',
    }


